import { sql } from "drizzle-orm";
import { bigint, boolean, char, check, date, foreignKey, index, integer, pgEnum, pgTable, text, timestamp, unique, uniqueIndex, uuid } from "drizzle-orm/pg-core";
import { growthLeads } from "./growth-leads.js";
import { users } from "./organization.js";

export const growthProposalStatus = pgEnum("growth_proposal_status", [
  "draft",
  "pending_approval",
  "approved",
  "rejected",
  "sent",
  "acceptance_pending",
  "accepted",
  "acceptance_refused",
  "withdrawn",
  "superseded",
  "won",
]);
export const growthAcceptanceMethod = pgEnum("growth_acceptance_method", ["signed_document", "email_confirmation", "written_message", "verbal"]);
export const growthConfirmationDecision = pgEnum("growth_confirmation_decision", ["confirmed", "refused"]);

/**
 * Status cache for a lead's single proposal (migration 0016). Written only by nested proposal triggers
 * (pg_trigger_depth() > 1); it always equals the latest growth_proposal_events row (deferred check).
 * The id is generated by the server. (current_version_id, id) references the versions table in SQL (deferred).
 */
export const growthProposals = pgTable(
  "growth_proposals",
  {
    id: uuid("id").primaryKey(),
    leadId: uuid("lead_id")
      .notNull()
      .unique("growth_proposals_lead_unique")
      .references(() => growthLeads.id),
    currentVersionId: uuid("current_version_id"),
    currentVersionNo: integer("current_version_no"),
    status: growthProposalStatus("status"),
    eventSeq: integer("event_seq").notNull().default(0),
    createdBy: uuid("created_by")
      .notNull()
      .references(() => users.id),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    unique("growth_proposals_id_lead_unique").on(t.id, t.leadId),
    index("growth_proposals_queue_idx").on(t.status).where(sql`status IN ('pending_approval', 'acceptance_pending')`),
    check("growth_proposals_seq_status", sql`(event_seq = 0) = (status IS NULL)`),
    check("growth_proposals_current_set", sql`(status IS NULL) = (current_version_id IS NULL) AND (status IS NULL) = (current_version_no IS NULL)`),
  ],
);

/** Immutable proposal versions. version_no, currency and created_at are set by trigger. */
export const growthProposalVersions = pgTable(
  "growth_proposal_versions",
  {
    id: uuid("id").primaryKey().default(sql`uuidv7()`),
    proposalId: uuid("proposal_id").notNull(),
    leadId: uuid("lead_id").notNull(),
    versionNo: integer("version_no").notNull(),
    documentUrl: text("document_url").notNull(),
    amountMinor: bigint("amount_minor", { mode: "number" }).notNull(),
    currency: char("currency", { length: 3 }).notNull().default("INR"),
    validUntil: date("valid_until", { mode: "string" }).notNull(),
    summary: text("summary").notNull(),
    createdBy: uuid("created_by")
      .notNull()
      .references(() => users.id),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    foreignKey({ name: "growth_proposal_versions_proposal_fk", columns: [t.proposalId, t.leadId], foreignColumns: [growthProposals.id, growthProposals.leadId] }),
    unique("growth_proposal_versions_number_unique").on(t.proposalId, t.versionNo),
    unique("growth_proposal_versions_id_proposal_unique").on(t.id, t.proposalId),
    unique("growth_proposal_versions_id_lead_unique").on(t.id, t.leadId),
    index("growth_proposal_versions_lead_idx").on(t.leadId),
    check("growth_proposal_versions_number_positive", sql`version_no >= 1`),
    check("growth_proposal_versions_document_https", sql`document_url ~ '^https://[^\\s/?#]+[^\\s]*$' AND char_length(document_url) <= 2000`),
    check("growth_proposal_versions_amount", sql`amount_minor BETWEEN 0 AND 100000000000`),
    check("growth_proposal_versions_currency_inr", sql`currency = 'INR'`),
    check("growth_proposal_versions_summary", sql`summary = btrim(summary) AND char_length(summary) BETWEEN 1 AND 2000`),
    check("growth_proposal_versions_valid_until", sql`valid_until >= ((created_at AT TIME ZONE 'UTC')::date - 1)`),
  ],
);

/** Append-only status events: the single source of proposal status. seq and created_at are set by trigger. */
export const growthProposalEvents = pgTable(
  "growth_proposal_events",
  {
    id: uuid("id").primaryKey().default(sql`uuidv7()`),
    proposalId: uuid("proposal_id").notNull(),
    versionId: uuid("version_id").notNull(),
    seq: integer("seq").notNull(),
    fromStatus: growthProposalStatus("from_status"),
    toStatus: growthProposalStatus("to_status").notNull(),
    actorId: uuid("actor_id")
      .notNull()
      .references(() => users.id),
    note: text("note"),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    foreignKey({ name: "growth_proposal_events_version_fk", columns: [t.versionId, t.proposalId], foreignColumns: [growthProposalVersions.id, growthProposalVersions.proposalId] }),
    unique("growth_proposal_events_seq_unique").on(t.proposalId, t.seq),
    uniqueIndex("growth_proposal_events_one_creation").on(t.versionId).where(sql`from_status IS NULL`),
    index("growth_proposal_events_version_idx").on(t.versionId),
    check("growth_proposal_events_creation", sql`(from_status IS NULL) = (to_status = 'draft')`),
    check("growth_proposal_events_note_required", sql`to_status NOT IN ('rejected', 'withdrawn', 'acceptance_refused') OR note IS NOT NULL`),
    check("growth_proposal_events_note", sql`note IS NULL OR (note = btrim(note) AND char_length(note) BETWEEN 1 AND 1000)`),
  ],
);

/** Append-only; one per version. late and needs_confirmation are computed by trigger. */
export const growthProposalAcceptances = pgTable(
  "growth_proposal_acceptances",
  {
    id: uuid("id").primaryKey().default(sql`uuidv7()`),
    proposalId: uuid("proposal_id").notNull(),
    versionId: uuid("version_id").notNull().unique("growth_proposal_acceptances_version_unique"),
    leadId: uuid("lead_id").notNull(),
    method: growthAcceptanceMethod("method").notNull(),
    evidenceUrl: text("evidence_url"),
    note: text("note"),
    acceptedOn: date("accepted_on", { mode: "string" }).notNull(),
    late: boolean("late").notNull(),
    needsConfirmation: boolean("needs_confirmation").notNull(),
    recordedBy: uuid("recorded_by")
      .notNull()
      .references(() => users.id),
    recordedAt: timestamp("recorded_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    foreignKey({ name: "growth_proposal_acceptances_version_fk", columns: [t.versionId, t.proposalId], foreignColumns: [growthProposalVersions.id, growthProposalVersions.proposalId] }),
    foreignKey({ name: "growth_proposal_acceptances_lead_fk", columns: [t.versionId, t.leadId], foreignColumns: [growthProposalVersions.id, growthProposalVersions.leadId] }),
    unique("growth_proposal_acceptances_id_version_unique").on(t.id, t.versionId),
    check("growth_proposal_acceptances_evidence", sql`method = 'verbal' OR evidence_url IS NOT NULL`),
    check("growth_proposal_acceptances_evidence_https", sql`evidence_url IS NULL OR (evidence_url ~ '^https://[^\\s/?#]+[^\\s]*$' AND char_length(evidence_url) <= 2000)`),
    check("growth_proposal_acceptances_verbal_note", sql`method <> 'verbal' OR note IS NOT NULL`),
    check("growth_proposal_acceptances_note", sql`note IS NULL OR (note = btrim(note) AND char_length(note) BETWEEN 1 AND 1000)`),
    check("growth_proposal_acceptances_needs_confirmation", sql`needs_confirmation = (method = 'verbal' OR late)`),
  ],
);

/** Append-only CEO decision on an acceptance that needs confirmation. proposal_id and version_id are derived. */
export const growthProposalConfirmations = pgTable(
  "growth_proposal_confirmations",
  {
    id: uuid("id").primaryKey().default(sql`uuidv7()`),
    acceptanceId: uuid("acceptance_id").notNull().unique("growth_proposal_confirmations_acceptance_unique"),
    proposalId: uuid("proposal_id").notNull(),
    versionId: uuid("version_id").notNull(),
    decision: growthConfirmationDecision("decision").notNull(),
    note: text("note"),
    actorId: uuid("actor_id")
      .notNull()
      .references(() => users.id),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    foreignKey({ name: "growth_proposal_confirmations_acceptance_fk", columns: [t.acceptanceId, t.versionId], foreignColumns: [growthProposalAcceptances.id, growthProposalAcceptances.versionId] }),
    foreignKey({ name: "growth_proposal_confirmations_version_fk", columns: [t.versionId, t.proposalId], foreignColumns: [growthProposalVersions.id, growthProposalVersions.proposalId] }),
    check("growth_proposal_confirmations_refusal_note", sql`decision = 'confirmed' OR note IS NOT NULL`),
    check("growth_proposal_confirmations_note", sql`note IS NULL OR (note = btrim(note) AND char_length(note) BETWEEN 1 AND 1000)`),
  ],
);
